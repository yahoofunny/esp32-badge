#!/usr/bin/env python3
"""Build a small CJK bitmap font from the characters a set of strings actually uses.

The system font is 8x8 ASCII, which cannot draw Chinese at all. Rather than shipping a
full CJK face -- tens of thousands of glyphs, hundreds of kilobytes -- this takes the
strings that are going to be drawn on the badge and rasterises only the characters they
contain. A tutorial of six short pages needs about forty-five, which is 1.5 KB.

Glyphs are 24x24, one bit per pixel, row-major, four bytes per row. 16 px was tried first
and dense characters -- the ones with a full-width radical on the left -- came out mushy
when scaled up; rasterising at the final size is what makes them legible.

The face is a system font (Microsoft YaHei by default). What is stored is a rasterised
subset of individual characters, the same arrangement the project's 8x8 font already uses;
regenerate from any TTF with --font.

    tools/make_cjk_font.py --text tools/help_text.txt --out system/assets_cjk.h
    tools/make_cjk_font.py --preview build/cjk_preview.png
"""

import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_FONT = r"C:\Windows\Fonts\msyh.ttc"     # Microsoft YaHei
DEFAULT_TEXT = os.path.join(ROOT, "tools", "help_text.txt")
DEFAULT_OUT = os.path.join(ROOT, "system", "assets_cjk.h")

GLYPH = 24
THRESHOLD = 96          # coverage above this counts as ink


def collect(path, extra):
    chars = set()
    if os.path.exists(path):
        for ch in open(path, encoding="utf-8").read():
            if ord(ch) > 0x7F and not ch.isspace():
                chars.add(ch)
    for ch in extra:
        if ord(ch) > 0x7F:
            chars.add(ch)
    return sorted(chars, key=ord)


def rasterise(font_path, codepoints):
    face = ImageFont.truetype(font_path, GLYPH)
    glyphs = {}
    for cp in codepoints:
        img = Image.new("L", (GLYPH, GLYPH), 0)
        draw = ImageDraw.Draw(img)
        # Anchor near the baseline centre so 16 px glyphs sit consistently.
        draw.text((0, 0), chr(cp), font=face, fill=255)
        rows = []
        for y in range(GLYPH):
            bits = 0
            for x in range(GLYPH):
                if img.getpixel((x, y)) > THRESHOLD:
                    bits |= 1 << (GLYPH - 1 - x)
            rows.append(bits)
        glyphs[cp] = rows
    return glyphs


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--text", default=DEFAULT_TEXT, help="file whose characters are kept")
    ap.add_argument("--extra", default="", help="more characters to include")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--preview", help="write a PNG of the glyphs for checking")
    args = ap.parse_args()

    if not os.path.exists(args.font):
        sys.exit(f"font not found: {args.font}")

    cps = [ord(c) for c in collect(args.text, args.extra)]
    if not cps:
        sys.exit("no characters to rasterise")
    glyphs = rasterise(args.font, cps)
    print(f"{len(cps)} glyphs from {os.path.basename(args.font)}")

    if args.preview:
        cols = 10
        rows = (len(cps) + cols - 1) // cols
        scale = 3
        img = Image.new("RGB", (cols * (GLYPH + 4) * scale, rows * (GLYPH + 16) * scale),
                        (0x10, 0x10, 0x18))
        draw = ImageDraw.Draw(img)
        for i, cp in enumerate(cps):
            gx = (i % cols) * (GLYPH + 4) * scale
            gy = (i // cols) * (GLYPH + 16) * scale
            for y, bits in enumerate(glyphs[cp]):
                for x in range(GLYPH):
                    if bits & (1 << (GLYPH - 1 - x)):
                        draw.rectangle([gx + x * scale, gy + y * scale,
                                        gx + (x + 1) * scale - 1, gy + (y + 1) * scale - 1],
                                       fill=(0xEC, 0xEC, 0xF4))
            draw.text((gx, gy + GLYPH * scale + 1), f"U+{cp:04X}", fill=(0x6E, 0x6E, 0x80))
        img.save(args.preview)
        print(f"wrote {args.preview}")

    lines = [
        "// Generated by tools/make_cjk_font.py -- do not edit by hand.",
        "//",
        f"// {len(cps)} characters used by the on-device help, {GLYPH}x{GLYPH} at one bit per",
        "// pixel, two bytes per row, most significant bit on the left. A full CJK face would",
        "// be tens of thousands of glyphs; this is only what the tutorial draws.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define CJK_GLYPH {GLYPH}",
        f"#define CJK_COUNT {len(cps)}",
        "",
        "static const uint16_t cjk_codepoints[CJK_COUNT] = {",
    ]
    for i in range(0, len(cps), 8):
        lines.append("    " + " ".join(f"0x{cp:04X}," for cp in cps[i:i + 8]))
    lines += ["};", "", "static const uint32_t cjk_bits[CJK_COUNT][CJK_GLYPH] = {"]
    for cp in cps:
        rows = glyphs[cp]
        lines.append(f"    {{ {', '.join(f'0x{b:06X}' for b in rows)} }},   // {chr(cp)}")
    lines.append("};")
    lines.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.out} ({len(cps) * GLYPH * 2} bytes of glyph data)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
