#!/usr/bin/env python3
"""Convert the blog's ASCII-art pet sprites into a firmware header.

The pet in `reference/tamagotchi/index.html` stores its art as arrays of strings,
one character per pixel. That is already a bitmap, so there is nothing to rasterise --
the characters just need renaming to palette indices and packing four to a byte.

Kept as a generator rather than a one-off edit so the art stays owned by the
original: change it there, re-run this, and the firmware follows.

    tools/convert_pet_sprites.py [source.html] [output.h]
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The source maps characters to CSS colours; these are the same colours as RGB565.
# Order defines the packed indices, so index 0 is always transparent.
CHAR_RGB = [
    (".", None),            # transparent
    ("B", (0xD7, 0x77, 0x57)),   # body
    ("E", (0x17, 0x12, 0x1C)),   # eyes
    ("W", (0xFF, 0xF6, 0xE8)),   # highlight
    ("C", (0xF3, 0xE0, 0xBD)),   # egg shell
    ("S", (0xE8, 0xA2, 0x4C)),   # egg spots
    ("X", (0x17, 0x12, 0x1C)),   # sick eyes (same colour as eyes, kept distinct)
]

SPRITE_NAMES = ["egg", "baby", "babySleep", "teen", "teenSleep", "adult", "adultSleep"]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def parse_sprites(html):
    m = re.search(r"var SPRITES = \{(.*?)\n\};", html, re.S)
    if not m:
        sys.exit("could not find SPRITES in the source")
    body = m.group(1)

    sprites = {}
    for sm in re.finditer(r"(\w+)\s*:\s*\[(.*?)\]", body, re.S):
        rows = re.findall(r'"([^"]*)"', sm.group(2))
        if rows:
            sprites[sm.group(1)] = rows
    return sprites


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?",
                    default=os.path.join(ROOT, "reference", "tamagotchi", "index.html"))
    ap.add_argument("output", nargs="?",
                    default=os.path.join(ROOT, "system", "assets_pet.h"))
    args = ap.parse_args()

    if not os.path.exists(args.source):
        sys.exit(f"source not found: {args.source}\n"
                 f"(it lives in the blog repo under public/games/tamagotchi/)")

    html = open(args.source, encoding="utf-8").read()
    sprites = parse_sprites(html)

    idx_of = {ch: i for i, (ch, _) in enumerate(CHAR_RGB)}

    lines = [
        "// Generated by tools/convert_pet_sprites.py -- do not edit.",
        "//",
        "// The clawd pet's sprites, taken from the ASCII-art original in the blog's",
        "// tamagotchi page. Each pixel is a 4-bit palette index, two pixels per byte,",
        "// low nibble first. Index 0 is transparent.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Palette, in palette-visible RGB565 (panel byte order is applied by the",
        "// renderer, not here).",
        "#define PET_PALETTE_COUNT %d" % len(CHAR_RGB),
        "static const uint16_t pet_palette[PET_PALETTE_COUNT] = {",
    ]
    for ch, rgb in CHAR_RGB:
        if rgb is None:
            lines.append("    0x0000,                  // transparent")
        else:
            lines.append(f"    0x{rgb565(*rgb):04X},                  // '{ch}'")
    lines.append("};")
    lines.append("")

    lines.append("typedef struct {")
    lines.append("    const uint8_t *bits;   // 4bpp indices, row-major")
    lines.append("    uint8_t        w;")
    lines.append("    uint8_t        h;")
    lines.append("    uint8_t        rowBytes;")
    lines.append("} pet_sprite_t;")
    lines.append("")

    total_bytes = 0
    emitted = []
    for name in SPRITE_NAMES:
        if name not in sprites:
            sys.exit(f"missing sprite in source: {name}")
        rows = sprites[name]
        h = len(rows)
        w = len(rows[0])
        for r in rows:
            if len(r) != w:
                sys.exit(f"{name}: ragged sprite ({len(r)} vs {w})")

        packed = []
        for r in rows:
            for i in range(0, w, 2):
                lo = idx_of.get(r[i], 0)
                hi = idx_of.get(r[i + 1], 0) if i + 1 < w else 0
                if r[i] not in idx_of or (i + 1 < w and r[i + 1] not in idx_of):
                    bad = r[i] if r[i] not in idx_of else r[i + 1]
                    sys.exit(f"{name}: unknown pixel character {bad!r}")
                packed.append((hi << 4) | lo)
        row_bytes = (w + 1) // 2
        total_bytes += len(packed)

        emitted.append(f"static const uint8_t pet_bits_{name}[{len(packed)}] = {{")
        for i in range(0, len(packed), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in packed[i:i + 16])
            emitted.append(f"    {chunk},")
        emitted.append("};")

    lines.extend(emitted)
    lines.append("")
    lines.append("// Indexed by the pet's life stage; the Sleep variants are used while it is")
    lines.append("// asleep.")
    lines.append("static const pet_sprite_t pet_sprites[PET_SPRITE_COUNT] = {")
    for name in SPRITE_NAMES:
        rows = sprites[name]
        row_bytes = (len(rows[0]) + 1) // 2
        lines.append(f"    {{ pet_bits_{name}, {len(rows[0])}, {len(rows)}, {row_bytes} }},   // {name}")
    lines.append("};")
    lines.append("")

    # Insert the count define before the array that uses it.
    for i, l in enumerate(lines):
        if l.startswith("typedef struct {"):
            lines.insert(i, "#define PET_SPRITE_COUNT %d" % len(SPRITE_NAMES))
            break

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    open(args.output, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    print(f"wrote {args.output}")
    for name in SPRITE_NAMES:
        rows = sprites[name]
        print(f"  {name:12s} {len(rows[0])}x{len(rows)}")
    print(f"  bitmap data: {total_bytes} bytes total")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
