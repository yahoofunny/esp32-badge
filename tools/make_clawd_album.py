#!/usr/bin/env python3
"""Embed unique original GIF bytes in flash; no resizing or image conversion."""
import argparse
import hashlib
from pathlib import Path
import zlib
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'system/assets_clawd_album.h'

def generate():
    files=[];seen=set()
    for path in sorted((ROOT/'assets/clawd-gifs').glob('*.gif')):
        data=path.read_bytes()
        digest=hashlib.sha256(data).digest()
        if digest in seen:continue
        seen.add(digest)
        if not data.startswith((b'GIF87a',b'GIF89a')):raise ValueError(path)
        files.append((path.name,data))
    if not files:raise ValueError('No Clawd GIFs found')
    lines=['// Generated by tools/make_clawd_album.py from assets/clawd-gifs.',
           '// Original bytes, AGPL-3.0; attribution in NOTICE.md. Stored in flash.',
           '#pragma once','#include "clawd_album.h"','namespace clawd_album {']
    for index,(_,data) in enumerate(files):
        lines.append(f'static const uint8_t GIF_{index}[] = {{')
        for offset in range(0,len(data),32):
            lines.append('    '+','.join(f'0x{v:02x}' for v in data[offset:offset+32])+',')
        lines.append('};')
    lines.append('static const Entry ALBUM[] = {')
    for index,(name,data) in enumerate(files):
        # Metadata only: the embedded GIF bytes remain completely unchanged.
        # Use the union of every animation frame so centering never follows a
        # moving limb or cuts off a later speech bubble.
        with Image.open(ROOT/'assets/clawd-gifs'/name) as im:
            boxes=[]
            for frame in range(im.n_frames):
                im.seek(frame)
                box=im.convert('RGBA').getbbox()
                if box:boxes.append(box)
            x=min(b[0] for b in boxes);y=min(b[1] for b in boxes)
            w=max(b[2] for b in boxes)-x;h=max(b[3] for b in boxes)-y
        lines.append(f'    {{"{name}",GIF_{index},{len(data)},0x{zlib.crc32(data):08x}u,{x},{y},{w},{h}}},')
    lines.extend(['};','} // namespace clawd_album',''])
    return '\n'.join(lines),files

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source,files=generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8')!=source:raise SystemExit('Clawd album header is stale')
    else:OUTPUT.write_text(source,encoding='utf-8',newline='\n')
    print(f'Clawd album: {len(files)} unique GIFs, {sum(len(data) for _,data in files):,} original bytes; '+('verified' if args.check else 'generated'))

if __name__=='__main__':main()
