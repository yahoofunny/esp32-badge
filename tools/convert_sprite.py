#!/usr/bin/env python3
"""Convert a flat-colour sprite into a 2-bit-per-pixel indexed C header.

Built for clawd, whose art is essentially two flat colours plus transparency:
body, eyes, and everything else transparent. Storing that as RGB565 would waste
16 bits per pixel on two distinct values; 2 bpp keeps even a full-resolution
378x253 sprite down to ~23 KB, so there is no reason to downscale and blur it.

Each pixel becomes a 2-bit index:
    0 = transparent
    1 = body colour   (--body, default red)
    2 = detail colour (--detail, default black, i.e. clawd's eyes)

Two optional extra indices are supported for sprites with more than two colours:
    3 = --extra (defaults to the body colour if unused)

Output layout: row-major, 4 pixels per byte, LSB-first (pixel 0 in bits 0-1),
each row padded up to a byte boundary. The renderer indexes it as
`bits[y * row_bytes + (x >> 2)] >> ((x & 3) * 2) & 3`.

Usage:
    tools/convert_sprite.py INPUT.png OUTPUT.h --name clawd
    tools/convert_sprite.py clawd.png out.h --name clawd --body FF3B30
"""

import argparse
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")


def rgb888_to_rgb565(r: int, g: int, b: int) -> int:
    """Standard little-endian RGB565 (matches LV_COLOR_16_SWAP 0 on this panel)."""
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def parse_hex_colour(value: str):
    value = value.lstrip("#").strip()
    if len(value) != 6:
        raise argparse.ArgumentTypeError(f"expected RRGGBB, got {value!r}")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", help="source image (PNG recommended; GIF/JPEG also work)")
    ap.add_argument("output", help="C header to write")
    ap.add_argument("--name", required=True, help="C symbol prefix, e.g. clawd")
    ap.add_argument("--body", type=parse_hex_colour, default=(0xE8, 0x3B, 0x3B),
                    help="body colour as RRGGBB (default E83B3B, red)")
    ap.add_argument("--detail", type=parse_hex_colour, default=(0x14, 0x0D, 0x0D),
                    help="detail/eye colour as RRGGBB (default 140D0D, near-black)")
    ap.add_argument("--extra", type=parse_hex_colour, default=None,
                    help="third colour as RRGGBB (optional; falls back to body colour)")
    ap.add_argument("--dark-threshold", type=int, default=100,
                    help="mean-channel cutoff below which a pixel counts as detail (default 100)")
    ap.add_argument("--alpha-threshold", type=int, default=128,
                    help="alpha at or above this counts as opaque (default 128)")
    args = ap.parse_args()

    im = Image.open(args.input).convert("RGBA")
    bbox = im.split()[3].getbbox()
    if bbox is None:
        return print("error: image is fully transparent") or 1
    im = im.crop(bbox)
    w, h = im.size
    print(f"source {args.input}: cropped to {w}x{h} (bbox {bbox})")

    rgb = im.convert("RGB").load()
    alpha = im.split()[3].load()

    row_bytes = (w + 3) // 4
    data = bytearray(row_bytes * h)
    counts = [0, 0, 0, 0]

    for y in range(h):
        base = y * row_bytes
        for x in range(w):
            if alpha[x, y] < args.alpha_threshold:
                idx = 0
            else:
                r, g, b = rgb[x, y]
                idx = 2 if (r + g + b) / 3 < args.dark_threshold else 1
            counts[idx] += 1
            data[base + (x >> 2)] |= idx << ((x & 3) * 2)

    pal_extra = args.extra if args.extra else args.body
    palettes = [None, args.body, args.detail, pal_extra]

    lines = [
        f"// Generated by tools/convert_sprite.py from {args.input} -- do not edit by hand.",
        f"// {w}x{h}, 2 bits per pixel, {len(data)} bytes of bitmap data.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define {args.name.upper()}_W {w}",
        f"#define {args.name.upper()}_H {h}",
        f"#define {args.name.upper()}_ROW_BYTES {row_bytes}",
        "",
        "// Palette indices: 0 = transparent, 1 = body, 2 = detail, 3 = extra.",
        f"#define {args.name.upper()}_PALETTE {{ 0x0000, "
        + ", ".join(f"0x{rgb888_to_rgb565(*c):04X}" for c in palettes[1:])
        + " }",
        "",
        "// Convenience accessors; the renderer only needs these three.",
        f"#define {args.name.upper()}_BODY_RGB565   0x{rgb888_to_rgb565(*args.body):04X}",
        f"#define {args.name.upper()}_DETAIL_RGB565 0x{rgb888_to_rgb565(*args.detail):04X}",
        "",
        f"static const uint8_t {args.name}_bits[{len(data)}] = {{",
    ]

    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("    " + " ".join(f"0x{b:02X}," for b in chunk))
    lines.append("};")
    lines.append("")

    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    total = w * h
    print(f"wrote {args.output}")
    print(f"  transparent {counts[0]:7d} ({100*counts[0]/total:5.1f}%)")
    print(f"  body        {counts[1]:7d} ({100*counts[1]/total:5.1f}%)  #{''.join(f'{c:02X}' for c in args.body)}"
          f" -> RGB565 0x{rgb888_to_rgb565(*args.body):04X}")
    print(f"  detail      {counts[2]:7d} ({100*counts[2]/total:5.1f}%)  #{''.join(f'{c:02X}' for c in args.detail)}"
          f" -> RGB565 0x{rgb888_to_rgb565(*args.detail):04X}")
    print(f"  bitmap {len(data)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
