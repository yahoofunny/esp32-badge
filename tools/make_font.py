#!/usr/bin/env python3
"""Bake an 8x8 bitmap font for ASCII 32..126 into a C header.

The system firmware renders text directly into its own framebuffer, so it cannot
lean on LVGL's font machinery. This produces the smallest thing that looks decent:
one byte per row, eight rows per glyph, MSB on the left, so drawing a character is
a table lookup and eight shifts per scanline.

    tools/make_font.py system/assets_font.h [--size 11] [--font path.ttf]
"""

import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126          # printable ASCII
CELL = 8

FALLBACKS = [
    r"C:\Windows\Fonts\consola.ttf",
    r"C:\Windows\Fonts\consolab.ttf",
    r"C:\Windows\Fonts\lucon.ttf",
    r"C:\Windows\Fonts\cour.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
]


def pick_font(explicit):
    if explicit:
        return explicit
    for p in FALLBACKS:
        if os.path.exists(p):
            return p
    sys.exit("no TrueType font found; pass --font")


def render_glyph(font, ch):
    """Rasterise one character into a CELL x CELL 1bpp cell, baselined consistently."""
    img = Image.new("L", (CELL * 2, CELL * 2), 0)
    d = ImageDraw.Draw(img)
    # Draw at a known origin with a fixed baseline so glyphs line up across rows.
    d.text((1, 1), ch, fill=255, font=font)
    bbox = img.getbbox()
    if bbox is None:
        return [0] * CELL
    glyph = img.crop(bbox)
    if glyph.width > CELL:
        glyph = glyph.resize((CELL, glyph.height), Image.LANCZOS)

    cell = Image.new("L", (CELL, CELL), 0)
    # Baseline-align: 1px descender room, so 'g' and 'y' hang below the x-height.
    top = max(0, CELL - 2 - glyph.height)
    cell.paste(glyph, (1 if glyph.width <= CELL - 2 else 0, top))

    rows = []
    for y in range(CELL):
        byte = 0
        for x in range(CELL):
            if cell.getpixel((x, y)) >= 110:
                byte |= 0x80 >> x
        rows.append(byte)
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("output", nargs="?", default="system/assets_font.h")
    ap.add_argument("--size", type=int, default=11, help="point size to rasterise at")
    ap.add_argument("--font", default=None)
    args = ap.parse_args()

    path = pick_font(args.font)
    font = ImageFont.truetype(path, args.size)

    out = [
        "// Generated by tools/make_font.py -- do not edit.",
        f"// Source: {os.path.basename(path)} @ {args.size}px, rasterised into {CELL}x{CELL} cells.",
        "//",
        "// One byte per row, eight rows per glyph, MSB = leftmost pixel, covering",
        f"// ASCII {FIRST}..{LAST}. Rows are top to bottom; the glyph is baseline-aligned with",
        "// one pixel of descender room.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_FIRST {FIRST}",
        f"#define FONT_LAST  {LAST}",
        f"#define FONT_CELL  {CELL}",
        "",
        f"static const uint8_t font8x8[FONT_LAST - FONT_FIRST + 1][{CELL}] = {{",
    ]

    for code in range(FIRST, LAST + 1):
        rows = render_glyph(font, chr(code))
        label = chr(code) if chr(code) != "\\" else "backslash"
        hexrows = ", ".join(f"0x{r:02X}" for r in rows)
        out.append(f"    {{{hexrows}}},   // {code:3d} '{label}'")

    out.append("};")
    out.append("")

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {args.output}  ({LAST - FIRST + 1} glyphs, "
          f"{(LAST - FIRST + 1) * CELL} bytes of bitmap data)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
